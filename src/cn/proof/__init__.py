"""CARD-23 Financial Claim Passport（对外：金融AI结论护照）.

把一个金融 Claim 变成**机器可验证的证明对象**，并由一个**不调用任何模型**的验证器
重新回答「这条结论现在还算数吗」。

    claim → FinancialProofObject（六块证明）
              ↑ build_financial_proof_object()
    verify_claim() → VerificationResult（五态：VERIFIED / DEGRADED / STALE / BLOCKED / CONFLICTED）

与「引用」的区别：普通 citation 只回答「这句话来自第几页」，FPO 还要回答
「数字对不对（重算）」「依赖还有效吗（CARD-09 传播）」「假设是什么口径（CARD-08）」
「是不是已经有更新的版本（CARD-13 版本谱系）」。

本包**不导入任何模型客户端**，``verify_claim`` 路径上没有任何模型调用 ——
§9 的契约是「验证结果不得被 LLM 修改」，最可靠的保证是验证路径里根本没有 LLM。
``tests/test_cn_proof.py`` 用源码级断言守住这一条。

快速开始::

    from src.cn.proof import ProofContext, verify_claim

    result = verify_claim("c1", ProofContext(graph=graph, run_id="run-1"))
    result.overall_status, result.status_reasons
"""

