def _ordered_metrics(metrics: Sequence[Any]) -> List[Any]:
    return sorted(metrics, key=lambda item: (str(getattr(item, "metric", "")), str(getattr(item, "period_key", ""))))


def _claim_for_metric(context: MemoContext, metric: Any) -> Optional[Claim]:
    if context.graph is None:
        return None
    return context.graph.fact_claim_for(
        str(getattr(metric, "metric", "")),
        str(getattr(metric, "period_key", "")) or None,
    )


def _signal_claim_id(context: MemoContext, signal: Any) -> Optional[str]:
    if context.graph is None:
        return None
    claims = context.graph.claims_for_signal(str(getattr(signal, "signal_id", "")))
    return claims[0].claim_id if claims else None


def _signal_metric(signal: Any) -> str:
    ids = tuple(getattr(signal, "metric_calculation_ids", ()) or ())
    return str(getattr(signal, "label", "") or (ids[0] if ids else ""))


def _finding_id(finding: Any) -> str:
    for attribute in ("finding_id", "check_id", "claim_id"):
        value = getattr(finding, attribute, None)
        if value:
            return str(value)
    if isinstance(finding, dict):
        for key in ("finding_id", "check_id", "claim_id"):
            if finding.get(key):
                return str(finding[key])
    return "finding:unknown"


def _valuation_verdict(context: MemoContext) -> Optional[MemoSentence]:
    valuation = context.valuation
    if valuation is None:
        return None
    status = str(getattr(valuation, "status", "") or "")
    if status == "blocked":
        return MemoSentence(
            sentence_span=f"估值结论被阻断（{getattr(valuation, 'blocked_reason', '') or '输入不可用'}），本备忘录不给出目标价。",
            claim_type=CLAIM_OPINION,
            assumption_note="系统性阻断说明，非数值结论",
        )
    if status == "assumption_only":
        return MemoSentence(
            sentence_span="本次估值全部依赖登记假设、无可溯源的 sourced 参数，仅作演示。",
            claim_type=CLAIM_OPINION,
            assumption_note="数据等级警示：纯假设演示",
        )
    return None


def _data_grade(context: MemoContext) -> str:
    analysis = context.analysis
    metrics = list(getattr(analysis, "metrics", ()) or ())
    if not any(getattr(item, "value", None) is not None for item in metrics):
        return GRADE_UNAVAILABLE
    valuation = context.valuation
    if valuation is not None:
        status = str(getattr(valuation, "status", "") or "")
        if status == "assumption_only":
            return GRADE_ASSUMPTION_ONLY
        if status == "blocked":
            return GRADE_MIXED
    if not getattr(analysis, "data_complete", False):
        return GRADE_MIXED
    return GRADE_SOURCED


def _memo_warnings(memo: InvestmentMemo, context: MemoContext) -> List[str]:
    warnings: List[str] = []
    if memo.data_grade == GRADE_ASSUMPTION_ONLY:
        warnings.append("valuation_is_assumption_only: 估值结论仅基于登记假设，不可当作事实。")
    if memo.data_grade == GRADE_UNAVAILABLE:
        warnings.append("no_metrics_available: 上游未产出任何可计算指标，备忘录不含财务结论。")
    graph = context.graph
    if graph is not None:
        report = graph.detect()
        if report.orphan_claims:
            warnings.append(f"graph_orphan_claims:{len(report.orphan_claims)}")
        if report.missing_evidence:
            warnings.append(f"graph_missing_evidence:{len(report.missing_evidence)}")
        blocked = [claim.claim_id for claim in graph.claims.values() if claim.validation_status == VALIDATION_BLOCKED]
        if blocked:
            warnings.append(f"graph_blocked_claims:{len(blocked)}")
    return warnings


def _blocked_claim_ids(graph: Optional[ClaimGraph]) -> List[str]:
    """Claims the graph currently refuses to conclude (§9: reported, not hidden)."""
    if graph is None:
        return []
    return sorted(
        claim.claim_id
        for claim in graph.claims.values()
        if claim.validation_status == VALIDATION_BLOCKED
    )


def _num(value: Any) -> str:
    """Deterministic number rendering (no locale, no float noise)."""
    if value is None:
        return "N/A"
    try:
        number = float(value)
    except (TypeError, ValueError):
        return str(value)
    if number == int(number) and abs(number) < 1e15:
        return str(int(number))
    return f"{number:.4f}".rstrip("0").rstrip(".")


