@dataclass(frozen=True)
class MemoSentence:
    """One sentence plus its tier marking.

    Exactly one of two shapes is legal, and the validator enforces it:

    * **assertion** — ``claim_type`` is ``fact`` / ``inference`` / ``opinion`` and
      the sentence states something about the company. A numeric assertion must
      bind a ``calculation_id`` or ``evidence_ids``;
    * **structural** — ``structural=True`` and ``claim_type`` is ``None``. This is
      template scaffolding (counts, page numbers, status labels, section
      boundaries), which asserts nothing and is therefore exempt from the numeric
      binding rule.

    ``claim_type=None`` **without** ``structural`` is an unmarked sentence and is
    rejected — that is the gap the sentence-level marking exists to close.
    """

    sentence_span: str
    claim_id: Optional[str] = None
    claim_type: Optional[str] = None
    calculation_id: Optional[str] = None
    derived_from: Tuple[str, ...] = ()
    assumption_note: Optional[str] = None
    evidence_ids: Tuple[str, ...] = ()
    citations: Tuple[Dict[str, Any], ...] = ()
    structural: bool = False

    @property
    def numeric(self) -> bool:
        return any(ch.isdigit() for ch in self.sentence_span)

    @property
    def is_assertion(self) -> bool:
        return not self.structural

    def to_dict(self) -> Dict[str, Any]:
        return {
            "sentence_span": self.sentence_span,
            "claim_id": self.claim_id,
            "claim_type": self.claim_type,
            "calculation_id": self.calculation_id,
            "derived_from": list(self.derived_from),
            "assumption_note": self.assumption_note,
            "evidence_ids": list(self.evidence_ids),
            "citations": [dict(item) for item in self.citations],
            "structural": self.structural,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "MemoSentence":
        return cls(
            sentence_span=str(data.get("sentence_span", "")),
            claim_id=data.get("claim_id"),
            claim_type=data.get("claim_type"),
            calculation_id=data.get("calculation_id"),
            derived_from=tuple(data.get("derived_from") or ()),
            assumption_note=data.get("assumption_note"),
            evidence_ids=tuple(data.get("evidence_ids") or ()),
            citations=tuple(dict(item) for item in (data.get("citations") or ())),
            structural=bool(data.get("structural", False)),
        )


@dataclass
class MemoSection:
    """One memo section with its sentence-level markings."""

    section_id: str
    title: str
    sentences: List[MemoSentence] = field(default_factory=list)
    data_status: str = STATUS_OK
    warnings: List[str] = field(default_factory=list)

    @property
    def body_markdown(self) -> str:
        return "".join(sentence.sentence_span for sentence in self.sentences)

    @property
    def tier_marking(self) -> List[Dict[str, Any]]:
        """The card's ``tier_marking`` view: sentence span + claim + type."""
        return [
            {
                "sentence_span": sentence.sentence_span,
                "claim_id": sentence.claim_id,
                "claim_type": sentence.claim_type,
            }
            for sentence in self.sentences
        ]

    @property
    def evidence_ids(self) -> List[str]:
        out: List[str] = []
        for sentence in self.sentences:
            for evidence_id in sentence.evidence_ids:
                if evidence_id not in out:
                    out.append(evidence_id)
        return out

    def to_dict(self) -> Dict[str, Any]:
        return {
            "section_id": self.section_id,
            "title": self.title,
            "data_status": self.data_status,
            "body_markdown": self.body_markdown,
            "tier_marking": self.tier_marking,
            "sentences": [sentence.to_dict() for sentence in self.sentences],
            "evidence_ids": self.evidence_ids,
            "warnings": list(self.warnings),
        }


@dataclass
class InvestmentMemo:
    """The assembled memo."""

    memo_id: str
    symbol: str
    document_id: str
    as_of: str
    sections: List[MemoSection] = field(default_factory=list)
    data_grade: str = GRADE_SOURCED
    warnings: List[str] = field(default_factory=list)
    disclaimers: List[str] = field(default_factory=list)
    graph_run_id: Optional[str] = None
    report_period: Optional[str] = None

    def section(self, section_id: str) -> Optional[MemoSection]:
        for item in self.sections:
            if item.section_id == section_id:
                return item
        return None

    @property
    def section_ids(self) -> List[str]:
        return [item.section_id for item in self.sections]

    @property
    def sentences(self) -> List[MemoSentence]:
        return [sentence for section in self.sections for sentence in section.sentences]

    @property
    def evidence_ids(self) -> List[str]:
        out: List[str] = []
        for section in self.sections:
            for evidence_id in section.evidence_ids:
                if evidence_id not in out:
                    out.append(evidence_id)
        return out

    def to_dict(self) -> Dict[str, Any]:
        return {
            "memo_id": self.memo_id,
            "symbol": self.symbol,
            "document_id": self.document_id,
            "report_period": self.report_period,
            "as_of": self.as_of,
            "data_grade": self.data_grade,
            "graph_run_id": self.graph_run_id,
            "section_ids": self.section_ids,
            "sections": [section.to_dict() for section in self.sections],
            "warnings": list(self.warnings),
            "disclaimers": list(self.disclaimers),
            "evidence_count": len(self.evidence_ids),
            "sentence_count": len(self.sentences),
        }


