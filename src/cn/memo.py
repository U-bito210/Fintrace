def _build_memo_prompt(
    section_name: str,
    analysis_dict: Dict[str, Any],
    valuation_dict: Dict[str, Any],
    existing_claim_ids: Iterable[str],
) -> str:
    """Prompt for a narrative section, carrying a claim-id whitelist.

    The model may only cite ids from ``existing_claim_ids``. Anything else is
    rejected by :func:`_validate_memo_segment_output`, so a hallucinated id can
    never reach the memo.
    """
    whitelist = sorted(str(item) for item in existing_claim_ids)
    return (
        "你是买方研究员的写作助手。请为投资备忘录的一个段落撰写中文句子。\n"
        f"段落：{section_name}\n"
        "硬性要求：\n"
        "1. 只能引用下列白名单中的 claim_id，禁止自造任何 id；\n"
        "2. 每条句子必须附逐字原句；\n"
        "3. 事实句 claim_type=fact 且 claim_id 必填；推论句 claim_type=inference 且 derived_from 非空；"
        "观点句 claim_type=opinion 且须给 assumption_note；\n"
        "4. 含数值的句子必须引用已存在的 calculation_id；\n"
        "5. 禁止编造任何未在下方数据中出现的数字。\n"
        f"claim_id 白名单：{json.dumps(whitelist, ensure_ascii=False)}\n"
        f"结构化分析数据：{json.dumps(analysis_dict, ensure_ascii=False, default=str)}\n"
        f"结构化估值数据：{json.dumps(valuation_dict, ensure_ascii=False, default=str)}\n"
        '返回 JSON 数组：[{"sentence_span": str, "claim_id": str|null, '
        '"claim_type": "fact"|"inference"|"opinion"|null, "derived_from": [str]|null, '
        '"calculation_id": str|null, "assumption_note": str|null}]'
    )


def _validate_memo_segment_output(
    sentences: Sequence[Any], existing_claim_ids: Iterable[str]
) -> None:
    """Hard-validate a narrator's output before it is written into the memo (§6).

    Raises :class:`MemoSegmentError` on the first violation — a bad segment is
    regenerated or dropped by the caller, never silently accepted.
    """
    whitelist = {str(item) for item in existing_claim_ids}
    for index, raw in enumerate(sentences):
        sentence = raw if isinstance(raw, MemoSentence) else MemoSentence.from_dict(dict(raw))
        if not (sentence.sentence_span or "").strip():
            raise MemoSegmentError(f"segment[{index}]: empty sentence_span")
        if sentence.structural:
            if sentence.claim_type is not None:
                raise MemoSegmentError(
                    f"segment[{index}]: structural scaffolding must not carry a claim_type"
                )
            continue
        if sentence.claim_type is None:
            raise MemoSegmentError(
                f"segment[{index}]: unmarked sentence (set claim_type or structural=True)"
            )
        if sentence.claim_id is not None and sentence.claim_id not in whitelist:
            raise MemoSegmentError(
                f"segment[{index}]: claim_id {sentence.claim_id!r} is not in the whitelist"
            )
        if sentence.claim_type not in (CLAIM_FACT, CLAIM_INFERENCE, CLAIM_OPINION):
            raise MemoSegmentError(f"segment[{index}]: unknown claim_type {sentence.claim_type!r}")
        if sentence.claim_type == CLAIM_FACT and not sentence.claim_id:
            raise MemoSegmentError(f"segment[{index}]: fact sentence requires a claim_id")
        if sentence.claim_type == CLAIM_INFERENCE and not sentence.derived_from:
            raise MemoSegmentError(f"segment[{index}]: inference sentence requires derived_from")
        if sentence.claim_type == CLAIM_OPINION and not (sentence.assumption_note or "").strip():
            raise MemoSegmentError(f"segment[{index}]: opinion sentence requires an assumption_note")
        if sentence.numeric and not (sentence.calculation_id or sentence.evidence_ids):
            raise MemoSegmentError(
                f"segment[{index}]: numeric sentence must bind a calculation_id or evidence"
            )


