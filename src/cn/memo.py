# Deterministic sections
# --------------------------------------------------------------------------- #
def _section_financial_performance(section: MemoSection, context: MemoContext) -> None:
    analysis = context.analysis
    metrics = list(getattr(analysis, "metrics", ()) or ())
    if not metrics:
        section.warnings.append("analysis_produced_no_metrics")
        return
    if context.graph is None:
        # Without the graph there is no claim to bind a sentence to, and this card
        # forbids an unbound numeric assertion — so the section states its gap.
        section.warnings.append("claim_graph_not_provided")
        return
    usable = [item for item in metrics if getattr(item, "value", None) is not None]
    bound = 0
    for metric in _ordered_metrics(usable):
        claim = _claim_for_metric(context, metric)
        if claim is None:
            # A metric with no fact claim cannot be marked; report, never fake.
            section.warnings.append(f"metric_without_claim:{metric.metric}:{metric.period_key}")
            continue
        bound += 1
        delta = getattr(metric, "delta_pct", None)
        comparison = ""
        if delta is not None and getattr(metric, "comparable", False):
            comparison = f"，同比 {_num(delta)}%"
        elif getattr(metric, "delta_abs", None) is not None:
            comparison = f"，变动 {_num(metric.delta_abs)} {getattr(metric, 'unit', '')}"
        unit = getattr(metric, "unit", "") or ""
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    f"{getattr(metric, 'label', '') or metric.metric}"
                    f"（{metric.period_key}）为 {_num(metric.value)} {unit}{comparison}。"
                ),
                claim_id=claim.claim_id,
                claim_type=CLAIM_FACT,
                calculation_id=getattr(metric, "calculation_id", None),
                evidence_ids=claim.evidence_ids,
            )
        )
    if not bound:
        section.sentences.clear()
        section.warnings.append("no_metric_bound_to_a_claim")
    if context.graph is not None:
        blocked = _blocked_claim_ids(context.graph)
        if blocked:
            section.warnings.append(f"blocked_claims:{len(blocked)}")


def _section_valuation(section: MemoSection, context: MemoContext) -> None:
    valuation = context.valuation
    if valuation is None:
        section.warnings.append("valuation_not_provided")
        return
    status = str(getattr(valuation, "status", "") or "")
    scenarios = list(getattr(valuation, "scenarios", ()) or ())
    applicable = [item for item in scenarios if getattr(item, "applicable", False)]

    section.sentences.append(
        MemoSentence(
            sentence_span=(
                f"相对估值状态：{status or 'unknown'}；"
                f"共 {len(scenarios)} 个方法×情景组合，其中 {len(applicable)} 个可用。"
            ),
            structural=True,
        )
    )
    first_calculation_id: Optional[str] = None
    for item in applicable:
        calculation_id = (tuple(getattr(item, "calculation_ids", ()) or ()) or (None,))[0]
        first_calculation_id = first_calculation_id or calculation_id
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    f"{getattr(item, 'method', '')}·{getattr(item, 'scenario', '')} 隐含价格区间 "
                    f"{_num(getattr(item, 'value_low', None))}–{_num(getattr(item, 'value_high', None))} 元"
                    f"（中值 {_num(getattr(item, 'value_mid', None))} 元）。"
                ),
                # A valuation output is an assumption-bearing estimate: it is an
                # opinion whose target multiples are registered assumptions.
                claim_type=CLAIM_OPINION,
                assumption_note="目标倍数与情景增速均为登记假设（见假设清单）",
                calculation_id=calculation_id,
            )
        )

    dispersion = getattr(valuation, "method_dispersion", None) or {}
    across = dispersion.get("across_methods") if isinstance(dispersion, dict) else None
    if across:
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    "各方法中值极差 "
                    f"{_num(across.get('range'))} 元（均值 {_num(across.get('mean'))} 元）："
                    "本备忘录分别列示，不给出合成的『最终区间』。"
                ),
                claim_type=CLAIM_OPINION,
                assumption_note="方法间离散度报告，非合成目标价",
                calculation_id=first_calculation_id,
            )
        )
    note = getattr(valuation, "applicability_note", None)
    if note:
        section.sentences.append(
            MemoSentence(sentence_span=str(note), structural=True)
        )
    for warning in getattr(valuation, "warnings", ()) or ():
        section.warnings.append(str(warning))
    if status == "assumption_only":
        section.warnings.append("assumption_only_valuation")


def _section_falsification(section: MemoSection, context: MemoContext) -> None:
    """Falsification must carry *computable* thresholds (card §10)."""
    analysis = context.analysis
    graph = context.graph
    signals = list(getattr(analysis, "signals", ()) or ())
    thresholds = [signal for signal in signals if getattr(signal, "threshold", None) is not None]
    for signal in thresholds:
        derived = tuple(
            claim.claim_id
            for claim in (graph.claims_for_signal(signal.signal_id) if graph is not None else [])
        )
        if not derived:
            # An inference with nothing to derive from would violate §7 — report it
            # rather than emit an unbound causal sentence.
            section.warnings.append(f"signal_without_claim:{signal.signal_id}")
            continue
        calculation_ids = tuple(getattr(signal, "metric_calculation_ids", ()) or ())
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    f"证伪条件：若「{getattr(signal, 'label', signal.signal_id)}」相关指标"
                    f"（{_signal_metric(signal)}）回升/跌破阈值 {_num(signal.threshold)}"
                    f"（当前观测 {_num(getattr(signal, 'observed', None))}，期间 {'/'.join(signal.periods)}），"
                    "则该逻辑的核心支撑不再成立。"
                ),
                claim_id=derived[0],
                claim_type=CLAIM_INFERENCE,
                calculation_id=(calculation_ids[0] if calculation_ids else None),
                derived_from=derived,
            )
        )

    valuation = context.valuation
    scenarios = list(getattr(valuation, "scenarios", ()) or ()) if valuation is not None else []
    bull = [
        item
        for item in scenarios
        if getattr(item, "applicable", False) and str(getattr(item, "scenario", "")) == "bull"
    ]
    for item in bull:
        calculation_id = (tuple(getattr(item, "calculation_ids", ()) or ()) or (None,))[0]
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    f"证伪条件：若股价高于 {getattr(item, 'method', '')} Bull 情景上限 "
                    f"{_num(getattr(item, 'value_high', None))} 元而盈利未同步上修，"
                    "则目标倍数假设失效。"
                ),
                claim_type=CLAIM_OPINION,
                assumption_note="来自 CARD-08 情景估值上限，阈值即该情景隐含价格",
                calculation_id=calculation_id,
            )
        )

    # A directional metric already carries a computable threshold: crossing zero.
    if graph is not None:
        for metric in _ordered_metrics(
            [item for item in (getattr(analysis, "metrics", ()) or ()) if getattr(item, "delta_pct", None) is not None]
        )[:5]:
            claim = _claim_for_metric(context, metric)
            if claim is None:
                continue
            section.sentences.append(
                MemoSentence(
                    sentence_span=(
                        f"证伪条件：若 {getattr(metric, 'label', '') or metric.metric} 同比增速跌破 0%"
                        f"（当前 {_num(metric.delta_pct)}%），则本期增长逻辑证伪。"
                    ),
                    claim_type=CLAIM_INFERENCE,
                    derived_from=(claim.claim_id,),
                    calculation_id=getattr(metric, "calculation_id", None),
                )
            )


def _section_tracking_kpis(section: MemoSection, context: MemoContext) -> None:
    analysis = context.analysis
    graph = context.graph
    metrics = [
        item
        for item in (getattr(analysis, "metrics", ()) or ())
        if getattr(item, "value", None) is not None
    ]
    for metric in _ordered_metrics(metrics)[:8]:
        claim = _claim_for_metric(context, metric)
        if claim is None:
            section.warnings.append(f"metric_without_claim:{metric.metric}:{metric.period_key}")
            continue
        section.sentences.append(
            MemoSentence(
                sentence_span=(
                    f"持续跟踪 {getattr(metric, 'label', '') or metric.metric}："
                    f"当前 {_num(metric.value)} {getattr(metric, 'unit', '') or ''}"
                    f"（{metric.period_key}），下期报告披露后以同一公式复核。"
                ),
                claim_id=claim.claim_id,
                claim_type=CLAIM_FACT,
                calculation_id=getattr(metric, "calculation_id", None),
                evidence_ids=claim.evidence_ids,
            )
        )
    if context.valuation is not None:
        section.sentences.append(
            MemoSentence(
                sentence_span="持续跟踪估值分位：新一期披露后重跑相对估值，比对本次方法离散度报告。",
                claim_type=CLAIM_OPINION,
                assumption_note="监测计划，非结论",
            )
        )
    if not section.sentences:
        section.warnings.append("no_trackable_metrics")


def _section_evidence_appendix(section: MemoSection, context: MemoContext) -> None:
    graph = context.graph
    if graph is None:
        section.warnings.append("claim_graph_not_provided")
        return
    entries = sorted(graph.evidence_index.values(), key=lambda item: item.evidence_id)
    if not entries:
        section.warnings.append("evidence_index_is_empty")
        return
    section.sentences.append(
        MemoSentence(
            sentence_span=f"本备忘录引用 {len(entries)} 条证据，全部可回溯到原始披露页或快照时点。",
            structural=True,
        )
    )
    for node in entries:
        location = (
            f"第 {node.page} 页" if node.page is not None else (node.available_at or "定位缺失")
        )
        section.sentences.append(
            MemoSentence(
                sentence_span=f"{node.evidence_id} → {node.metric or ''} {location}。",
                evidence_ids=(node.evidence_id,),
                structural=True,
            )
        )


# --------------------------------------------------------------------------- #
# Default (deterministic) narrator
# --------------------------------------------------------------------------- #
def template_narrator(section_id: str, context: MemoContext) -> List[MemoSentence]:
    """Deterministic narrative rendering — the offline default (§6).

    It *selects* existing claims rather than composing new prose, so every
    sentence is bound by construction and the memo is byte-reproducible with no
    model in the loop. An LLM narrator may replace it, but only within the same
    contract.
    """
    if section_id == SECTION_EXECUTIVE_SUMMARY:
        return _narrate_executive_summary(context)
    if section_id == SECTION_COMPANY_OVERVIEW:
        return _narrate_company_overview(context)
    if section_id == SECTION_INVESTMENT_THESIS:
        return _narrate_thesis(context)
    if section_id == SECTION_RISKS:
        return _narrate_risks(context)
    if section_id == SECTION_COUNTER_THESIS:
        return _narrate_counter_thesis(context)
    if section_id == SECTION_CATALYSTS:
        return _narrate_catalysts(context)
    return []


def _narrate_executive_summary(context: MemoContext) -> List[MemoSentence]:
    analysis = context.analysis
    out: List[MemoSentence] = []
    metrics = [item for item in (getattr(analysis, "metrics", ()) or ()) if getattr(item, "value", None) is not None]
    ranked = _ordered_metrics(metrics)
    for metric in ranked[:3]:
        claim = _claim_for_metric(context, metric)
        if claim is None:
            continue
        out.append(
            MemoSentence(
                sentence_span=f"{getattr(metric, 'label', '') or metric.metric}为 {_num(metric.value)} {getattr(metric, 'unit', '') or ''}。",
                claim_id=claim.claim_id,
                claim_type=CLAIM_FACT,
                calculation_id=getattr(metric, "calculation_id", None),
                evidence_ids=claim.evidence_ids,
            )
        )
    complete = bool(getattr(analysis, "data_complete", False))
    out.append(
        MemoSentence(
            sentence_span=(
                "本期分析数据完整，全部指标均由确定性计算产出。"
                if complete
                else "本期分析存在缺失输入，相关指标留空并在对应段落标注，未做任何填补。"
            ),
            claim_type=CLAIM_OPINION,
            assumption_note="对本次覆盖范围的判断，不涉及数值外推",
        )
    )
    verdict = _valuation_verdict(context)
    if verdict is not None:
        out.append(verdict)
    findings = list(context.findings or ())
    if findings:
        out.append(
            MemoSentence(
                # A meta-statement about the review itself, not about the company:
                # structural scaffolding, exempt from the numeric binding rule.
                sentence_span=f"本次同时在研报草稿中检出 {len(findings)} 处陈述与披露事实不符。",
                evidence_ids=tuple(_finding_id(item) for item in findings),
                structural=True,
            )
        )
    return out


def _narrate_company_overview(context: MemoContext) -> List[MemoSentence]:
    analysis = context.analysis
    out: List[MemoSentence] = [
        MemoSentence(
            sentence_span=(
                f"本备忘录覆盖的报告期为 {getattr(analysis, 'report_period', None) or '未识别'}，"
                f"会计口径为 {getattr(analysis, 'scope', None) or '未标注'}，"
                f"币种 {getattr(analysis, 'currency', None) or 'CNY'}。"
            ),
            structural=True,
        )
    ]
    for hit in list(context.hits or ())[:3]:
        text = str(getattr(hit, "text", "") or "").strip()
        claim_id = getattr(hit, "claim_id", None)
        if not text or not claim_id:
            # A retrieval hit is not a claim by itself. Without a claim to bind it
            # to, the quote is reported rather than presented as a fact sentence.
            continue
        out.append(
            MemoSentence(
                # Verbatim quote — the validator checks it against the CARD-06 hit.
                sentence_span=f"公告/年报原文：「{text}」。",
                claim_id=str(claim_id),
                claim_type=CLAIM_FACT,
                evidence_ids=(str(getattr(hit, "chunk_id", "")),),
                citations=(
                    {
                        "chunk_id": str(getattr(hit, "chunk_id", "")),
                        "mode": CITATION_QUOTE,
                        "quote": text,
                    },
                ),
            )
        )
    return out


def _narrate_thesis(context: MemoContext) -> List[MemoSentence]:
    graph = context.graph
    analysis = context.analysis
    out: List[MemoSentence] = []
    if graph is not None:
        for claim in sorted(graph.inferences, key=lambda item: item.claim_id):
            if not claim.derived_from:
                continue  # structurally unsupported; the graph validator flags it
            calculation_id, evidence_ids = _inference_binding(graph, claim)
            out.append(
                MemoSentence(
                    sentence_span=f"{claim.text}（依据：{'、'.join(claim.derived_from)}）。",
                    claim_id=claim.claim_id,
                    claim_type=CLAIM_INFERENCE,
                    derived_from=claim.derived_from,
                    calculation_id=calculation_id,
                    evidence_ids=evidence_ids,
                )
            )
    if not out and not list(getattr(analysis, "signals", ()) or ()):
        out.append(
            MemoSentence(
                sentence_span="本期未触发任何诊断信号，暂无可陈述的投资逻辑。",
                claim_type=CLAIM_OPINION,
                assumption_note="无信号不等于无风险，仅表示规则未命中",
            )
        )
    return out


def _narrate_risks(context: MemoContext) -> List[MemoSentence]:
    graph = context.graph
    out: List[MemoSentence] = []
    if graph is not None:
        for claim in sorted(graph.inferences, key=lambda item: item.claim_id):
            if not claim.derived_from:
                continue
            calculation_id, evidence_ids = _inference_binding(graph, claim)
            out.append(
                MemoSentence(
                    sentence_span=f"风险提示：{claim.text}。",
                    claim_id=claim.claim_id,
                    claim_type=CLAIM_INFERENCE,
                    derived_from=claim.derived_from,
                    calculation_id=calculation_id,
                    evidence_ids=evidence_ids,
                )
            )
        for claim in sorted(graph.claims.values(), key=lambda item: item.claim_id):
            if claim.validation_status != VALIDATION_BLOCKED:
                continue
            calculation_id, evidence_ids = _inference_binding(graph, claim)
            out.append(
                MemoSentence(
                    sentence_span=f"该结论目前被系统判定为 blocked（证据不可用）：{claim.text}。",
                    claim_id=claim.claim_id,
                    claim_type=CLAIM_OPINION,
                    assumption_note="状态陈述：证据缺失即不下结论",
                    calculation_id=calculation_id,
                    evidence_ids=evidence_ids,
                )
            )
    if not out:
        out.append(
            MemoSentence(
                sentence_span="未触发诊断信号，且不存在 blocked 结论；这不等于无风险。",
                claim_type=CLAIM_OPINION,
                assumption_note="无信号 = 规则未命中，不等于风险不存在",
            )
        )
    return out


def _narrate_counter_thesis(context: MemoContext) -> List[MemoSentence]:
    graph = context.graph
    out: List[MemoSentence] = []
    for claim_id in context.counter_claims:
        claim = context.claim(claim_id)
        if claim is None:
            continue
        if graph is not None:
            calculation_id, evidence_ids = _inference_binding(graph, claim)
        else:
            calculation_id, evidence_ids = None, claim.evidence_ids
        out.append(
            MemoSentence(
                sentence_span=f"反向证据：{claim.text}。",
                claim_id=claim.claim_id,
                claim_type=CLAIM_INFERENCE,
                derived_from=claim.derived_from or (claim.claim_id,),
                calculation_id=calculation_id,
                evidence_ids=evidence_ids,
            )
        )
    if not out:
        # Card §8 edge case 5: state the absence rather than manufacture a thesis.
        out.append(
            MemoSentence(
                sentence_span="未发现显著反向证据：诊断信号、估值边界与配额限制数量内均未出现与主逻辑相左的可用证据。",
                claim_type=CLAIM_OPINION,
                assumption_note="如实陈述检索范围有限，不构成『不存在反向证据』的断言",
            )
        )
    return out


def _narrate_catalysts(context: MemoContext) -> List[MemoSentence]:
    hits = list(context.hits or ())
    if not hits:
        return []
    out: List[MemoSentence] = []
    for hit in hits[:3]:
        text = str(getattr(hit, "text", "") or "").strip()
        if not text:
            continue
        chunk_id = str(getattr(hit, "chunk_id", ""))
        out.append(
            MemoSentence(
                sentence_span=f"潜在催化剂（据已检索披露）：「{text}」。",
                claim_type=CLAIM_OPINION,
                assumption_note="催化剂判断属分析师主观视角，非披露事实",
                # Bind the quoted chunk so a numeric quote still satisfies §10.
                evidence_ids=(chunk_id,) if chunk_id else (),
                citations=({"chunk_id": chunk_id, "mode": CITATION_QUOTE, "quote": text},),
            )
        )
    return out


def _inference_binding(graph: ClaimGraph, claim: Claim) -> Tuple[Optional[str], Tuple[str, ...]]:
    """The calculation / evidence a downstream sentence inherits.

    A sentence *about* a claim may bind either the claim's own calculations and
    evidence or those of its upstreams — a derived metric such as
    ``free_cash_flow`` binds only its calculation, while an *inference* binds
    only ``derived_from``. Both are collected here so a numeric sentence is
    never rendered without a trail (§10).
    """
    calculation_id: Optional[str] = claim.calculation_ids[0] if claim.calculation_ids else None
    evidence: List[str] = [item for item in claim.evidence_ids]
    for upstream_id in claim.derived_from:
        upstream = graph.claims.get(upstream_id)
        if upstream is None:
            continue
        calculation_id = calculation_id or (
            upstream.calculation_ids[0] if upstream.calculation_ids else None
        )
        for evidence_id in upstream.evidence_ids:
            if evidence_id not in evidence:
                evidence.append(evidence_id)
    return calculation_id, tuple(evidence)


