"""CARD-10 Investment Memo（买方投资备忘录）.

Assembles the system's final deliverable from what the rest of the chain already
produced:

    AnalysisResult (CARD-03) + ValuationResult (CARD-08) + Finding[] (CARD-05)
    + SearchHit[] (CARD-06) + ClaimGraph (CARD-09)  ->  InvestmentMemo

Design decisions that matter:

* **Sentence-level tier marking.** Every sentence in the memo carries a
  :class:`MemoSentence` marking it as ``fact`` / ``inference`` / ``opinion`` with
  the ``claim_id`` it maps to in the CARD-09 graph. Section-level marking (the v2
  design) let a factual section smuggle an opinion; sentence level does not.
* **No Multi-Agent dependency.** The narrative sections are rendered by a
  *narrator* callable whose default is a deterministic template over existing
  claims. An LLM narrator may be injected, but its output must pass
  :func:`_validate_memo_segment_output` first — it may only cite claim ids from
  the injected whitelist, never invent one.
* **No fabricated numbers.** Numeric sections are rendered from the deterministic
  templates; a narrative sentence containing a number must bind a calculation or
  evidence, otherwise the validator rejects the memo.
* **The memo does not hide what the system does not know.** A blocked claim is
  labelled ``blocked``; a missing upstream makes its section
  ``data_unavailable``; an all-assumption valuation raises a warning banner.
"""

