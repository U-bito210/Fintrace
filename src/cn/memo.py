def render_memo_markdown(memo: InvestmentMemo) -> str:
    """Render the memo to Markdown (sentences + a per-section marking table)."""
    lines: List[str] = []
    lines.append(f"# 投资备忘录 · {memo.symbol or memo.document_id}")
    lines.append("")
    lines.append(
        f"- 报告期：{memo.report_period or '未识别'} ｜ 数据等级：{memo.data_grade} "
        f"｜ 句子数：{len(memo.sentences)} ｜ 证据数：{len(memo.evidence_ids)}"
    )
    if memo.graph_run_id:
        lines.append(f"- 主张-证据图谱 run_id：{memo.graph_run_id}")
    lines.append("")
    for section in memo.sections:
        lines.append(f"## {section.title}（{section.section_id}）")
        lines.append("")
        if section.data_status != STATUS_OK:
            lines.append(f"> 数据状态：**{section.data_status}** —— 本节不提供结论。")
            lines.append("")
        lines.append(section.body_markdown or "（本节无内容）")
        lines.append("")
        if section.sentences:
            lines.append("| 逐句标注 | claim_id | 类型 | 计算 | 假设 |")
            lines.append("|---|---|---|---|---|")
            for sentence in section.sentences:
                span = sentence.sentence_span.replace("|", "\\|")
                lines.append(
                    f"| {span} | {sentence.claim_id or '—'} | {sentence.claim_type or '—'} | "
                    f"{sentence.calculation_id or '—'} | {sentence.assumption_note or '—'} |"
                )
            lines.append("")
        for warning in section.warnings:
            lines.append(f"- ⚠️ {warning}")
        if section.warnings:
            lines.append("")
    lines.append("## 免责与适用边界")
    lines.append("")
    for note in memo.disclaimers:
        lines.append(f"- {note}")
    if memo.warnings:
        lines.append("")
        lines.append("## 系统提示")
        lines.append("")
        for warning in memo.warnings:
            lines.append(f"- ⚠️ {warning}")
    return "\n".join(lines).rstrip() + "\n"


def render_memo_json(memo: InvestmentMemo) -> Dict[str, Any]:
    """Render the memo as JSON (same content as the Markdown)."""
    return memo.to_dict()


