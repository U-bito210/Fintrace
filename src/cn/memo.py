@dataclass
class MemoContext:
    """Everything a narrator may look at. Never a raw model transcript."""

    analysis: Any = None
    valuation: Any = None
    graph: Optional[ClaimGraph] = None
    findings: Sequence[Any] = ()
    hits: Sequence[Any] = ()
    symbol: str = ""
    document_id: str = ""
    as_of: str = ""
    counter_claims: Sequence[str] = ()

    def claim(self, claim_id: str) -> Optional[Claim]:
        if self.graph is None:
            return None
        return self.graph.claims.get(claim_id)


Narrator = Callable[[str, MemoContext], List[MemoSentence]]


# --------------------------------------------------------------------------- #
# Build
# --------------------------------------------------------------------------- #
def build_memo(
    analysis: Any,
    *,
    valuation: Any = None,
    graph: Optional[ClaimGraph] = None,
    findings: Sequence[Any] = (),
    hits: Sequence[Any] = (),
    symbol: str = "",
    document_id: str = "",
    as_of: str = "",
    counter_claims: Sequence[str] = (),
    narrator: Optional[Narrator] = None,
    memo_id: str = "",
) -> InvestmentMemo:
    """Assemble the eleven sections.

    ``narrator`` renders the narrative sections. The default is
    :func:`template_narrator` — a deterministic selection over existing claims,
    so the whole memo is reproducible offline with no model in the loop.
    """
    context = MemoContext(
        analysis=analysis,
        valuation=valuation,
        graph=graph,
        findings=tuple(findings or ()),
        hits=tuple(hits or ()),
        symbol=symbol or str(getattr(analysis, "document_id", "") or ""),
        document_id=document_id or str(getattr(analysis, "document_id", "") or ""),
        as_of=as_of,
        counter_claims=tuple(counter_claims or ()),
    )
    render_narrative = narrator or template_narrator

    sections: List[MemoSection] = []
    for section_id in SECTION_IDS:
        if section_id in NARRATIVE_SECTIONS:
            sections.append(_narrative_section(section_id, context, render_narrative))
        else:
            sections.append(_deterministic_section(section_id, context))

    memo = InvestmentMemo(
        memo_id=memo_id or f"memo-{context.document_id or context.symbol or 'unknown'}",
        symbol=context.symbol,
        document_id=context.document_id,
        report_period=getattr(analysis, "report_period", None),
        as_of=context.as_of,
        sections=sections,
        data_grade=_data_grade(context),
        warnings=[],
        disclaimers=[DISCLAIMER, BOUNDARY_NOTE],
        graph_run_id=graph.run_id if graph is not None else None,
    )
    memo.warnings.extend(_memo_warnings(memo, context))
    return memo


def _narrative_section(
    section_id: str, context: MemoContext, render: Narrator
) -> MemoSection:
    try:
        raw = list(render(section_id, context) or ())
    except MemoSegmentError:
        raise
    except Exception as exc:  # a broken narrator must not silently empty a section
        raise MemoError(f"narrator failed for {section_id}: {exc}") from exc

    existing = set(context.graph.claims) if context.graph is not None else set()
    section = MemoSection(section_id=section_id, title=SECTION_TITLES[section_id])
    for index, item in enumerate(raw):
        sentence = item if isinstance(item, MemoSentence) else MemoSentence.from_dict(dict(item))
        try:
            # Card §6: a violating sentence is re-generated or *dropped*, never
            # written into the memo — and the drop is recorded, not silent.
            _validate_memo_segment_output([sentence], existing)
        except MemoSegmentError as exc:
            section.warnings.append(f"rejected_sentence[{index}]:{exc}")
            continue
        section.sentences.append(sentence)

    if not section.sentences:
        section.data_status = STATUS_DATA_UNAVAILABLE
        section.warnings.append(f"no_evidence_for_section:{section_id}")
    return section


def _deterministic_section(section_id: str, context: MemoContext) -> MemoSection:
    builder = {
        SECTION_FINANCIAL_PERFORMANCE: _section_financial_performance,
        SECTION_VALUATION: _section_valuation,
        SECTION_FALSIFICATION: _section_falsification,
        SECTION_TRACKING_KPIS: _section_tracking_kpis,
        SECTION_EVIDENCE_APPENDIX: _section_evidence_appendix,
    }[section_id]
    section = MemoSection(section_id=section_id, title=SECTION_TITLES[section_id])
    builder(section, context)
    if not section.sentences:
        section.data_status = STATUS_DATA_UNAVAILABLE
        section.warnings.append(f"no_data_for_section:{section_id}")
    return section


