"""CARD-25 — Temporal Revalidation Engine（时间重验证引擎）。

新财报 / 更正公告 / 重述 / 新快照进入系统后，算出**哪些结论受影响**并**只重算那一片**。

```
Source Changed ↓ Evidence superseded/conflict ↓ Calculation stale
             ↓ Claim stale/blocked ↓ Thesis affected ↓ Valuation affected ↓ Memo section affected
```

- :mod:`src.cn.temporal.models` —— 语义词表与数据模型（四态血缘在这里，
  **不扩 CARD-02 的 ``Version``**；三态变化词表**来自 CARD-13**，本包不重定义）。
- :mod:`src.cn.temporal.lineage` —— append-only 版本谱系，替代判定调用 CARD-13 ``classify_change``。
- :mod:`src.cn.temporal.engine` —— 限深子图、**子图内有界重算**、与全量重算现场对账、影响与动作。

**零 LLM**：受影响判定与状态传播全是确定性图算法（卡 §9）。LLM 至多参与
"受影响备忘段落的改写"，那发生在本包之后，且本包不调用任何模型。
"""

